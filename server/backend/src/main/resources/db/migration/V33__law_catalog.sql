-- 法律法规清单模块（用户 2026-11-11 需求：展示目前制度引用的法规列表）
-- refs 列存 JSON 数组：[{"type":"module|tpl|doc","name":"被引用的制度/台账/范本名"}]
CREATE TABLE IF NOT EXISTS `law_catalog` (
    `id`             BIGINT       NOT NULL,
    `tenant_id`      BIGINT       NOT NULL DEFAULT 0,
    `law_name`       VARCHAR(200) NOT NULL,
    `law_no`         VARCHAR(120) NOT NULL DEFAULT '' COMMENT '令号/文号',
    `law_level`      VARCHAR(20)  NOT NULL DEFAULT '法律' COMMENT '法律/行政法规/部门规章/规范性文件',
    `category`       VARCHAR(40)  NOT NULL DEFAULT '综合安全',
    `version_label`  VARCHAR(120) NOT NULL DEFAULT '' COMMENT '版本说明，如 2021 修正 / 2023 第五次修订',
    `effective_date` VARCHAR(10)  NOT NULL DEFAULT '' COMMENT '现行版施行日期',
    `status`         VARCHAR(20)  NOT NULL DEFAULT 'active' COMMENT 'active 使用中 / superseded 待更新 / repealed 已废止',
    `apply_scope`    VARCHAR(20)  NOT NULL DEFAULT 'all' COMMENT 'all 通用 / danger 仅危货',
    `summary`        VARCHAR(500) NOT NULL DEFAULT '',
    `refs`           TEXT         COMMENT '引用本法规的制度/台账/范本 JSON',
    `sort_no`        INT          NOT NULL DEFAULT 0,
    `created_at`     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `created_by`     BIGINT       NOT NULL DEFAULT 0,
    `deleted`        TINYINT      NOT NULL DEFAULT 0,
    PRIMARY KEY (`id`),
    KEY `idx_tenant` (`tenant_id`, `deleted`, `sort_no`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '法律法规清单（制度引用的法规）';

