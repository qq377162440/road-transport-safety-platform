/* ============ 名称 → 文档 路由 ============ */

function pick(name) {
  const n = name || ''
  if (n.includes('责任制') || n.includes('责任书')) return docResponsibility()
  if (n.includes('承诺书')) return docCommitment()
  if (n.includes('制度') || n.includes('操作规程') || n.includes('制度汇编')) return docPolicy()
  if (n.includes('应急预案')) return docEmergency()
  if (n.includes('风险评估') || n.includes('应急资源')) return docRiskAssess()
  if (n.includes('风险辨识') || n.includes('风险告知') || n.includes('风险分级')) return docRiskIdentify()
  if (n.includes('隐患排查')) return docDangerCheck()
  if (n.includes('培训') || n.includes('教育')) return docTraining()
  if (n.includes('会议')) return docMeeting()
  if (n.includes('安全费用') || n.includes('提取') || n.includes('使用台账') || n.includes('营收入')) return docCost()
  if (n.includes('动态监控') || n.includes('在线率') || n.includes('月报') || n.includes('设备故障')) return docMonitor()
  if (n.includes('三检')) return docDailyCheck()
  if (n.includes('事故')) return docAccident()
  if (n.includes('组织架构') || n.includes('任命书') || n.includes('成立') || n.includes('通知')) return docAppointment(n.includes('组织架构') ? 'org' : (n.includes('通知') || n.includes('成立') ? 'notice' : 'appoint'))
  if (n.includes('营业执照')) return docCert('license')
  if (n.includes('经营许可证')) return docCert('permit')
  if (n.includes('产权') || n.includes('租赁') || n.includes('停车场') || n.includes('平面图')) return docCert('property')
  if (n.includes('责任险') || n.includes('保险') || n.includes('保单')) return docCert('insurance')
  return docGeneric(name)
}

export function getArchiveDoc(name) {
  return pick(name)
}

// 判断是否为「证照留存页」类型（上传类，正文即扫描件）
export function isCertPage(sections) {
  return sections && sections.length === 1 && sections[0].type === 'cert'
}
